  const topics = JSON.parse(fs.readFileSync(topicsPath, 'utf8')).filter(function (t) { return !isChemTopic(t); });
  const newTopics = buildTopics();
  topics.push.apply(topics, newTopics);

  const depsPath = DATA('dependencies.json');
  const deps = JSON.parse(fs.readFileSync(depsPath, 'utf8')).filter(function (d) {
    return String(d.topicId || '').indexOf('cnch_') !== 0 && String(d.prerequisiteId || '').indexOf('cnch_') !== 0;
  });
  EDGES.forEach(function (e) {
    deps.push({ topicId: e[0], prerequisiteId: e[1], strength: e[2], reason: e[3] });
  });

  const qPath = DATA('questions.json');
  const questions = JSON.parse(fs.readFileSync(qPath, 'utf8')).filter(function (q) {
    return String(q.topicId || '').indexOf('cnch_') !== 0;
  });
  const newQuestions = buildQuestions();
  questions.push.apply(questions, newQuestions);

  const stdPath = DATA('cn-curriculum-standards.json');
  const std = JSON.parse(fs.readFileSync(stdPath, 'utf8'));
  std.items = (std.items || []).filter(function (it) { return String(it.id || '').indexOf('cch-') !== 0; });
  std.items.push.apply(std.items, buildStandards());
  std.chemistry_senior = {
    title: '普通高中化学课程标准（2017年版2020年修订）',
    issuer: '中华人民共和国教育部',
    stage: '高中',
    year: 2020,
    revision: '2017年版2020年修订',
    url: 'https://www.moe.gov.cn/',
    textbook: '人民教育出版社 2019 年版高中化学（必修第一册、必修第二册、选择性必修1、2、3）',
    note: '条目为公开转述，未与课标纸本逐字核对；章节按人教版 2019 年版教材。'
  };

  fs.writeFileSync(topicsPath, JSON.stringify(topics, null, 2) + '\n');
  fs.writeFileSync(depsPath, JSON.stringify(deps, null, 2) + '\n');
  fs.writeFileSync(qPath, JSON.stringify(questions, null, 2) + '\n');
